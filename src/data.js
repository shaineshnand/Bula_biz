export function fjd(n) {
  const value = Math.round(Number(n) || 0);
  return `FJD ${value.toLocaleString("en-US")}`;
}

export function decorate(business, pledges) {
  const extra = pledges
    .filter((p) => p.id === business.id)
    .reduce((sum, p) => sum + p.amount, 0);
  const raisedNow = business.goal
    ? Math.min(business.goal, business.raised + extra)
    : 0;
  const left = business.goal ? business.goal - raisedNow : null;
  const pct = business.goal ? Math.round((raisedNow / business.goal) * 100) : 0;
  return {
    ...business,
    raisedNow,
    left,
    pct,
    funded: Boolean(business.goal) && left === 0,
  };
}

export function matchFilter(business, filter) {
  switch (filter) {
    case "women":
      return business.womenLed;
    case "food":
      return business.sector === "Food" || business.sector === "Hospitality";
    case "land":
      return business.sector === "Fishing" || business.sector === "Agriculture";
    case "diaspora":
      return business.diaspora;
    case "almost":
      return business.goal && business.pct >= 75 && business.pct < 100;
    case "scale":
      return business.tier === "scale";
    case "starting":
      return business.tier === "start";
    case "open":
      return Boolean(business.goal) && business.pct < 100;
    case "all":
    default:
      return true;
  }
}

